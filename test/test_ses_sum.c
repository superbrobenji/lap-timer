/* test_ses_sum.c -- .sum assembly byte-contract (spec §12.5).
 *
 * logger.c's rebuild_sum() writes HDR + VENUE + accumulated LAP frames + accumulated DRAG_RUN
 * frames + [END] to the .sum file. Session A1 (docs/.../2026-09-20-plan-dram-reclaim.md, Task 1)
 * replaces its single 4 KB assemble-then-emit scratch buffer with sequential writes of the same
 * sections to the open fd -- the bytes on storage must be byte-identical.
 *
 * The app-layer logger component is not part of the host build (test/CMakeLists.txt links core
 * only), so this test locks the CONTRACT at the layer that produces the bytes: the real core ses
 * encoders plus the exact §12.5 section order. It proves (a) the single-buffer assembly equals a
 * frozen golden captured from pre-refactor code, and (b) streaming the identical sections one at a
 * time to a sequential sink -- exactly what the refactored rebuild_sum does -- yields the same
 * golden byte-for-byte. If either the encoders or the assembly order ever drift, this fails. */
