/* Build the representative session fixtures rebuild_sum would hold at .sum time. */
static void fill_hdr(ses_hdr_t *h)
{
    memset(h, 0, sizeof *h);
    strcpy(h->session_id, "S00042_007");
    h->mode = 1; h->variant = 0; h->venue_id = 0x1234; h->layout_id = 0x0002;
    strcpy(h->fw, "v1.2.3-abcdef0"); strcpy(h->hwid, "ESP32-NEO6M-0001");
    h->log_profile = 0; h->fused_hz = 20; h->gps_hz = 10; h->start_gps_us = 1726800000000000LL;
    for (int i = 0; i < 9; i++) h->r_e4[i] = (int16_t)(1000 + i);
    for (int i = 0; i < 3; i++) h->gbias[i] = (int16_t)(-5 + i);
    h->calib_flags = 0x03;
}

/* lap_acc / drag_acc are opaque pre-encoded frame blobs that rebuild_sum copies verbatim; their
 * deterministic content only needs to be reproduced identically by both assembly strategies. */
static void fill_accumulators(uint8_t *lap, size_t lap_n, uint8_t *drag, size_t drag_n)
{
    for (size_t i = 0; i < lap_n; i++)  lap[i]  = (uint8_t)(0x40 + i * 7);
    for (size_t i = 0; i < drag_n; i++) drag[i] = (uint8_t)(0x80 + i * 11);
}

#define LAP_N  213u
#define DRAG_N 71u

/* Reference: the original single-buffer assemble-then-emit path. */
static size_t assemble_single_buffer(uint8_t *buf, size_t cap)
{
    ses_hdr_t h; fill_hdr(&h);
    uint8_t lap[LAP_N], drag[DRAG_N]; fill_accumulators(lap, LAP_N, drag, DRAG_N);
    size_t off = 0; int n;
    n = ses_encode_hdr(&h, buf + off, cap - off);                     TEST_ASSERT_GREATER_THAN(0, n); off += (size_t)n;
    n = ses_encode_venue(h.venue_id, h.layout_id, "Kyalami GP", buf + off, cap - off); TEST_ASSERT_GREATER_THAN(0, n); off += (size_t)n;
    memcpy(buf + off, lap, LAP_N);  off += LAP_N;
    memcpy(buf + off, drag, DRAG_N); off += DRAG_N;
    n = ses_encode_end(1726800600000000LL, 2, buf + off, cap - off);  TEST_ASSERT_GREATER_THAN(0, n); off += (size_t)n;
    return off;
}

/* A sequential byte sink standing in for the open .sum fd (one append == one sto_write). */
typedef struct { uint8_t bytes[4096]; size_t len; } sink_t;
static void sink_write(sink_t *s, const uint8_t *p, size_t n)
{
    TEST_ASSERT_LESS_OR_EQUAL(sizeof s->bytes, s->len + n);
    memcpy(s->bytes + s->len, p, n); s->len += n;
}

/* The refactored path: encode each section into a small local frame (<= FRAME_TMP_CAP) and stream
 * it straight to the fd; stream the accumulators from their own storage. No 4 KB scratch. */
static void assemble_streamed(sink_t *s)
{
    ses_hdr_t h; fill_hdr(&h);
    uint8_t lap[LAP_N], drag[DRAG_N]; fill_accumulators(lap, LAP_N, drag, DRAG_N);
    uint8_t frame[256]; int n;
    n = ses_encode_hdr(&h, frame, sizeof frame);                      TEST_ASSERT_GREATER_THAN(0, n); sink_write(s, frame, (size_t)n);
    n = ses_encode_venue(h.venue_id, h.layout_id, "Kyalami GP", frame, sizeof frame); TEST_ASSERT_GREATER_THAN(0, n); sink_write(s, frame, (size_t)n);
    sink_write(s, lap, LAP_N);
    sink_write(s, drag, DRAG_N);
    n = ses_encode_end(1726800600000000LL, 2, frame, sizeof frame);   TEST_ASSERT_GREATER_THAN(0, n); sink_write(s, frame, (size_t)n);
}

static void test_single_buffer_assembly_matches_golden(void)
{
    uint8_t buf[4096];
    size_t off = assemble_single_buffer(buf, sizeof buf);
    TEST_ASSERT_EQUAL_size_t(sizeof k_golden_sum, off);
    TEST_ASSERT_EQUAL_UINT8_ARRAY(k_golden_sum, buf, off);
}

static void test_streamed_assembly_is_byte_identical_to_golden(void)
{
    sink_t s; s.len = 0;
    assemble_streamed(&s);
    TEST_ASSERT_EQUAL_size_t(sizeof k_golden_sum, s.len);
    TEST_ASSERT_EQUAL_UINT8_ARRAY(k_golden_sum, s.bytes, s.len);
}

int main(void)
{
    UNITY_BEGIN();
    RUN_TEST(test_single_buffer_assembly_matches_golden);
    RUN_TEST(test_streamed_assembly_is_byte_identical_to_golden);
    return UNITY_END();
}
